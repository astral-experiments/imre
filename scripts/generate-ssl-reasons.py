"""Extract SSL-library reason mnemonics from CPython 3.14.5's OpenSSL 3.5.6 table.

Pass Modules/_ssl_data_35.h from CPython v3.14.5, commit
5607950ef232dad16d75c0cf53101d9649d89115 (see licenses/CPython.txt).
"""

import hashlib
from pathlib import Path
import re
import sys


def main():
    header = Path(sys.argv[1]).read_bytes()
    if hashlib.sha256(header).hexdigest() != "285d2d814e21c9b679e38f018188390dcae7cc412bdcb73a220101de9290a369":
        raise SystemExit("Expected CPython 3.14.5 Modules/_ssl_data_35.h")
    reasons = {}
    # The fallback row for each SSL_R_* macro carries its numeric library and reason.
    for name, number in re.findall(r'\{"([A-Z0-9_]+)", 20, (\d+)\}', header.decode()):
        code = int(number)
        if reasons.setdefault(code, name) != name:
            raise ValueError(f"conflicting mnemonics for SSL reason {code}")
    lines = [
        "// Generated by scripts/generate-ssl-reasons.py from CPython 3.14.5 / OpenSSL 3.5.6.",
        "pub(super) fn reason_name(reason: u32) -> Option<&'static str> {",
        "    Some(match reason {",
        *(f'        {code} => "{name}",' for code, name in sorted(reasons.items())),
        "        _ => return None,",
        "    })",
        "}",
    ]
    root = Path(__file__).resolve().parents[1]
    output = root / "crates/imre-runtime/src/dynamic/stdlib/ssl/provider/reasons.rs"
    output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
