"""Generate the UCD 3.2 properties used by CPython 3.14.5's unicodedata and Nameprep."""

from itertools import groupby
from pathlib import Path
import sys
import unicodedata


def category_change(char):
    old = unicodedata.ucd_3_2_0.category(char)
    return old if old != unicodedata.category(char) else ""


def write_property(out, name, property):
    # Each u32 holds the start point in its upper bits and a five-bit value index.
    values = []
    boundaries = []
    for value, group in groupby(range(sys.maxunicode + 1), key=lambda n: property(chr(n))):
        if value not in values:
            values.append(value)
        boundaries.append((next(group) << 5) | values.index(value))
    assert len(values) <= 32
    print(f'const {name}_VALUES: &[&str] = &[', file=out)
    print("    " + ", ".join(f'"{v}"' for v in values) + ",", file=out)
    print("];", file=out)
    print(f'const {name}: &[u32] = &[', file=out)
    for i in range(0, len(boundaries), 8):
        print("    " + ", ".join(f"0x{n:x}" for n in boundaries[i:i+8]) + ",", file=out)
    print("];", file=out)


if __name__ == "__main__":
    old = unicodedata.ucd_3_2_0
    if (sys.implementation.name, sys.version_info[:3], unicodedata.unidata_version, old.unidata_version) != (
        "cpython", (3, 14, 5), "16.0.0", "3.2.0"
    ):
        raise SystemExit("Generate with stock CPython 3.14.5")
    root = Path(__file__).resolve().parents[1]
    with (root / "crates/imre-runtime/native/ucd3.2.rs").open("w", encoding="ascii", newline="\n") as out:
        print("// Generated by scripts/generate_unicode_3_2.py from CPython 3.14.5.", file=out)
        write_property(out, "CATEGORY", category_change)
        write_property(out, "BIDI", old.bidirectional)
