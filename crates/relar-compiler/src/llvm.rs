//! Ownership lowering and textual LLVM emission, with no C or interpreter layer.

use std::fmt::Write;

use crate::ir::{Binary, Builtin, Compare, Expr, ExprKind, Function, Module, Statement, Type};

impl Type {
    fn llvm(self) -> &'static str {
        match self {
            Self::Int => "i64",
            Self::Bool => "i1",
            Self::Str | Self::ListInt => "ptr",
            Self::None => "i8",
        }
    }

    fn initial(self) -> &'static str {
        match self {
            Self::Int => "1",
            Self::Str | Self::ListInt => "null",
            Self::Bool | Self::None => "0",
        }
    }
}

struct Value {
    ty: Type,
    operand: String,
}

pub(crate) fn emit(module: &Module, sanitize: bool) -> String {
    let mut emitter = Emitter {
        code: String::new(),
        strings: Vec::new(),
        next_value: 0,
        next_label: 0,
        current: "entry".to_owned(),
        terminated: false,
        loops: Vec::new(),
        locals: Vec::new(),
        sanitize,
    };
    for (id, function) in module.functions.iter().enumerate() {
        emitter.function(function, &format!("fn_{id}"), false);
    }
    emitter.function(&module.entry, "main", true);
    let mut output = String::from(
        "; Generated by Relar. Runtime arguments borrow; results transfer ownership.\n",
    );
    output.push_str(DECLARATIONS);
    output.push_str(&integer_helpers());
    for (id, bytes) in emitter.strings.iter().enumerate() {
        write!(
            output,
            "@str_{id} = private unnamed_addr constant [{} x i8] c\"",
            bytes.len()
        )
        .unwrap();
        for byte in bytes {
            write!(output, "\\{byte:02X}").unwrap();
        }
        output.push_str("\"\n");
    }
    output.push_str(&emitter.code);
    output
}

struct Emitter {
    code: String,
    strings: Vec<Vec<u8>>,
    next_value: usize,
    next_label: usize,
    current: String,
    terminated: bool,
    loops: Vec<(String, String)>,
    locals: Vec<Type>,
    sanitize: bool,
}

impl Emitter {
    fn line(&mut self, line: impl AsRef<str>) {
        writeln!(self.code, "  {}", line.as_ref()).unwrap();
    }

    fn instruction(&mut self, instruction: impl AsRef<str>) -> String {
        let result = format!("%v{}", self.next_value);
        self.next_value += 1;
        self.line(format!("{result} = {}", instruction.as_ref()));
        result
    }

    fn label(&mut self) -> String {
        let result = format!("b{}", self.next_label);
        self.next_label += 1;
        result
    }

    fn start(&mut self, label: &str) {
        writeln!(self.code, "{label}:").unwrap();
        self.current = label.to_owned();
        self.terminated = false;
    }

    fn jump(&mut self, label: &str) {
        self.line(format!("br label %{label}"));
        self.terminated = true;
    }

    fn branch(&mut self, condition: &str, yes: &str, no: &str) {
        self.line(format!("br i1 {condition}, label %{yes}, label %{no}"));
        self.terminated = true;
    }

    fn call(&mut self, name: &str, returns: Type, args: &[&Value]) -> Value {
        let args = args
            .iter()
            .map(|value| format!("{} {}", value.ty.llvm(), value.operand))
            .collect::<Vec<_>>()
            .join(", ");
        Value {
            ty: returns,
            operand: self.instruction(format!("call {} @{name}({args})", returns.llvm())),
        }
    }

    fn void_call(&mut self, name: &str, args: &[&Value]) {
        let args = args
            .iter()
            .map(|value| format!("{} {}", value.ty.llvm(), value.operand))
            .collect::<Vec<_>>()
            .join(", ");
        self.line(format!("call void @{name}({args})"));
    }

    fn retain(&mut self, value: &Value) {
        let name = match value.ty {
            Type::Int => "retain_int",
            Type::Str => "relar_str_retain",
            Type::ListInt => "relar_list_retain",
            Type::Bool | Type::None => return,
        };
        self.void_call(name, &[value]);
    }

    fn release(&mut self, value: &Value) {
        let name = match value.ty {
            Type::Int => "release_int",
            Type::Str => "relar_str_release",
            Type::ListInt => "relar_list_release",
            Type::Bool | Type::None => return,
        };
        self.void_call(name, &[value]);
    }

    /// Acquires a reference so later evaluation may safely replace the source slot.
    fn load(&mut self, slot: usize) -> Value {
        let value = self.borrow_slot(slot);
        self.retain(&value);
        value
    }

    fn borrow_slot(&mut self, slot: usize) -> Value {
        let ty = self.locals[slot];
        Value {
            ty,
            operand: self.instruction(format!("load {}, ptr %local{slot}", ty.llvm())),
        }
    }

    /// Publishes the new owned value before releasing the replaced reference.
    fn store(&mut self, slot: usize, value: &Value) {
        let old = self.borrow_slot(slot);
        self.line(format!(
            "store {} {}, ptr %local{slot}",
            value.ty.llvm(),
            value.operand
        ));
        self.release(&old);
    }

    fn cleanup(&mut self) {
        for slot in 0..self.locals.len() {
            let value = self.borrow_slot(slot);
            self.release(&value);
        }
    }

    /// Roots borrowed arguments in initialized local slots and cleans up on every return.
    fn function(&mut self, function: &Function, symbol: &str, entry: bool) {
        self.locals = function.locals.clone();
        self.loops.clear();
        let params = function
            .params
            .iter()
            .enumerate()
            .map(|(i, &slot)| format!("{} %arg{i}", function.locals[slot].llvm()))
            .collect::<Vec<_>>()
            .join(", ");
        let returns = if entry {
            "i32"
        } else {
            function.returns.llvm()
        };
        let linkage = if entry { "" } else { "internal " };
        let attributes = if self.sanitize {
            " sanitize_address"
        } else {
            ""
        };
        writeln!(
            self.code,
            "\ndefine {linkage}{returns} @{symbol}({params}){attributes} {{"
        )
        .unwrap();
        self.start("entry");
        for (slot, &ty) in function.locals.iter().enumerate() {
            self.line(format!("%local{slot} = alloca {}", ty.llvm()));
            self.line(format!(
                "store {} {}, ptr %local{slot}",
                ty.llvm(),
                ty.initial()
            ));
        }
        for (i, &slot) in function.params.iter().enumerate() {
            let value = Value {
                ty: function.locals[slot],
                operand: format!("%arg{i}"),
            };
            self.retain(&value);
            self.store(slot, &value);
        }
        self.block(&function.body);
        if !self.terminated {
            self.cleanup();
            self.line(format!("ret {returns} 0"));
        }
        self.code.push_str("}\n");
    }

    fn block(&mut self, statements: &[Statement]) {
        for statement in statements {
            if self.terminated {
                break;
            }
            self.statement(statement);
        }
    }

    fn statement(&mut self, statement: &Statement) {
        match statement {
            Statement::Assign(slot, expression) => {
                let value = self.expr(expression);
                self.store(*slot, &value);
            }
            Statement::SetItem(list, index, expression) => {
                // Python evaluates an assignment's RHS before its target expressions.
                let value = self.expr(expression);
                let list = self.expr(list);
                let index = self.expr(index);
                self.void_call("relar_list_set", &[&list, &index, &value]);
                self.release(&value);
                self.release(&index);
                self.release(&list);
            }
            Statement::AugmentItem(list, index, op, expression) => {
                // Augmented assignment instead roots the target and old item first.
                let list = self.expr(list);
                let index = self.expr(index);
                let old = self.call("relar_list_get", Type::Int, &[&list, &index]);
                let right = self.expr(expression);
                let value = self.binary(*op, &old, &right);
                self.void_call("relar_list_set", &[&list, &index, &value]);
                for value in [&value, &right, &old, &index, &list] {
                    self.release(value);
                }
            }
            Statement::Expr(expression) => {
                let value = self.expr(expression);
                self.release(&value);
            }
            Statement::Return(expression) => {
                let value = self.expr(expression);
                self.cleanup();
                self.line(format!("ret {} {}", value.ty.llvm(), value.operand));
                self.terminated = true;
            }
            Statement::If(test, yes, no) => {
                let test = self.expr(test);
                let (yes_label, no_label, end) = (self.label(), self.label(), self.label());
                self.branch(&test.operand, &yes_label, &no_label);
                self.start(&yes_label);
                self.block(yes);
                let yes_ends = self.terminated;
                if !yes_ends {
                    self.jump(&end);
                }
                self.start(&no_label);
                self.block(no);
                let no_ends = self.terminated;
                if !no_ends {
                    self.jump(&end);
                }
                self.start(&end);
                if yes_ends && no_ends {
                    self.line("unreachable");
                    self.terminated = true;
                }
            }
            Statement::While(test, body) => {
                let (condition, body_label, end) = (self.label(), self.label(), self.label());
                self.jump(&condition);
                self.start(&condition);
                let test = self.expr(test);
                self.branch(&test.operand, &body_label, &end);
                self.start(&body_label);
                self.loops.push((end.clone(), condition.clone()));
                self.block(body);
                self.loops.pop();
                if !self.terminated {
                    self.jump(&condition);
                }
                self.start(&end);
            }
            Statement::For {
                target,
                cursor,
                stop,
                step,
                args,
                body,
            } => {
                let mut args = args.iter().map(|arg| self.expr(arg)).collect::<Vec<_>>();
                if args.len() == 1 {
                    args.insert(0, small(0));
                }
                if args.len() == 2 {
                    args.push(small(1));
                }
                for (&slot, value) in [*cursor, *stop, *step].iter().zip(&args) {
                    self.store(slot, value);
                }
                let zero = self.compare(Compare::Equal, &args[2], &small(0));
                let (fail, condition, body_label, increment, end) = (
                    self.label(),
                    self.label(),
                    self.label(),
                    self.label(),
                    self.label(),
                );
                self.branch(&zero.operand, &fail, &condition);
                self.start(&fail);
                self.line("call void @relar_range_step_zero()");
                self.line("unreachable");
                self.start(&condition);
                let current = self.load(*cursor);
                let stop_value = self.load(*stop);
                let step_value = self.load(*step);
                let positive = self.compare(Compare::Greater, &step_value, &small(0));
                let below = self.compare(Compare::Less, &current, &stop_value);
                let above = self.compare(Compare::Greater, &current, &stop_value);
                let test = self.instruction(format!(
                    "select i1 {}, i1 {}, i1 {}",
                    positive.operand, below.operand, above.operand
                ));
                for value in [&current, &stop_value, &step_value] {
                    self.release(value);
                }
                self.branch(&test, &body_label, &end);
                self.start(&body_label);
                let current = self.load(*cursor);
                self.store(*target, &current);
                self.loops.push((end.clone(), increment.clone()));
                self.block(body);
                self.loops.pop();
                if !self.terminated {
                    self.jump(&increment);
                }
                self.start(&increment);
                let current = self.load(*cursor);
                let step_value = self.load(*step);
                let next = self.binary(Binary::Add, &current, &step_value);
                self.store(*cursor, &next);
                self.release(&current);
                self.release(&step_value);
                self.jump(&condition);
                self.start(&end);
            }
            Statement::Break => self.jump(&self.loops.last().unwrap().0.clone()),
            Statement::Continue => self.jump(&self.loops.last().unwrap().1.clone()),
            Statement::Assert(test) => {
                let test = self.expr(test);
                let (success, fail) = (self.label(), self.label());
                self.branch(&test.operand, &success, &fail);
                self.start(&fail);
                self.line("call void @relar_assert_fail()");
                self.line("unreachable");
                self.start(&success);
            }
        }
    }

    fn literal(&mut self, contents: &str, ty: Type) -> Value {
        let id = self.strings.len();
        self.strings.push(contents.as_bytes().to_vec());
        let function = if ty == Type::Int {
            "relar_int_literal"
        } else {
            "relar_str_literal"
        };
        Value {
            ty,
            operand: self.instruction(format!(
                "call {} @{function}(ptr @str_{id}, i64 {})",
                ty.llvm(),
                contents.len()
            )),
        }
    }

    /// Produces an owned result; its consumer must transfer or release that ownership.
    fn expr(&mut self, expression: &Expr) -> Value {
        match &expression.kind {
            ExprKind::Int(value) => {
                if let Ok(value) = value.parse::<i64>()
                    && (-(1_i64 << 62)..(1_i64 << 62)).contains(&value)
                {
                    small(value)
                } else {
                    self.literal(value, Type::Int)
                }
            }
            ExprKind::Bool(value) => Value {
                ty: Type::Bool,
                operand: u8::from(*value).to_string(),
            },
            ExprKind::Str(value) => self.literal(value, Type::Str),
            ExprKind::None => none(),
            ExprKind::Local(slot) => self.load(*slot),
            ExprKind::List(values) => {
                let list = self.call("relar_list_new", Type::ListInt, &[]);
                for value in values {
                    let value = self.expr(value);
                    self.void_call("relar_list_append", &[&list, &value]);
                    self.release(&value);
                }
                list
            }
            ExprKind::Binary(op, left, right) => {
                let left = self.expr(left);
                let right = self.expr(right);
                let result = self.binary(*op, &left, &right);
                self.release(&left);
                self.release(&right);
                result
            }
            ExprKind::Negate(value) => {
                let value = self.expr(value);
                let result = self.binary(Binary::Subtract, &small(0), &value);
                self.release(&value);
                result
            }
            ExprKind::Not(value) => {
                let value = self.expr(value);
                Value {
                    ty: Type::Bool,
                    operand: self.instruction(format!("xor i1 {}, true", value.operand)),
                }
            }
            ExprKind::Boolean(and, values) => self.boolean(*and, values),
            ExprKind::Compare(values, ops) => self.comparisons(values, ops),
            ExprKind::Call(id, args) => {
                let args = args.iter().map(|arg| self.expr(arg)).collect::<Vec<_>>();
                let result = self.call(
                    &format!("fn_{id}"),
                    expression.ty,
                    &args.iter().collect::<Vec<_>>(),
                );
                for arg in &args {
                    self.release(arg);
                }
                result
            }
            ExprKind::Builtin(builtin, args) => self.builtin(builtin, args),
        }
    }

    fn binary(&mut self, op: Binary, left: &Value, right: &Value) -> Value {
        match op {
            Binary::Repeat => {
                let (list, count) = if left.ty == Type::ListInt {
                    (left, right)
                } else {
                    (right, left)
                };
                self.call("relar_list_repeat", Type::ListInt, &[list, count])
            }
            Binary::Add => self.call("int_add", Type::Int, &[left, right]),
            Binary::Subtract => self.call("int_sub", Type::Int, &[left, right]),
            Binary::Multiply => self.call("int_mul", Type::Int, &[left, right]),
            Binary::FloorDivide | Binary::Modulo => {
                let op = if matches!(op, Binary::FloorDivide) {
                    3
                } else {
                    4
                };
                Value {
                    ty: Type::Int,
                    operand: self.instruction(format!(
                        "call i64 @relar_int_binary(i64 {}, i64 {}, i32 {op})",
                        left.operand, right.operand
                    )),
                }
            }
        }
    }

    fn compare(&mut self, op: Compare, left: &Value, right: &Value) -> Value {
        let predicate = match op {
            Compare::Equal => "eq",
            Compare::NotEqual => "ne",
            Compare::Less => "slt",
            Compare::LessEqual => "sle",
            Compare::Greater => "sgt",
            Compare::GreaterEqual => "sge",
        };
        let operand = match left.ty {
            Type::Int => {
                let order = self.instruction(format!(
                    "call i32 @compare_int(i64 {}, i64 {})",
                    left.operand, right.operand
                ));
                self.instruction(format!("icmp {predicate} i32 {order}, 0"))
            }
            Type::Str => {
                let equal = self.instruction(format!(
                    "call i8 @relar_str_equal(ptr {}, ptr {})",
                    left.operand, right.operand
                ));
                let predicate = if matches!(op, Compare::Equal) {
                    "ne"
                } else {
                    "eq"
                };
                self.instruction(format!("icmp {predicate} i8 {equal}, 0"))
            }
            Type::Bool | Type::None => self.instruction(format!(
                "icmp {predicate} {} {}, {}",
                left.ty.llvm(),
                left.operand,
                right.operand
            )),
            Type::ListInt => unreachable!("list comparison is rejected by the frontend"),
        };
        Value {
            ty: Type::Bool,
            operand,
        }
    }

    /// Keeps a chain's middle operand rooted until its final comparison completes.
    fn comparisons(&mut self, values: &[Expr], ops: &[Compare]) -> Value {
        let end = self.label();
        let mut incoming = Vec::new();
        let mut left = self.expr(&values[0]);
        for (i, &op) in ops.iter().enumerate() {
            let right = self.expr(&values[i + 1]);
            let test = self.compare(op, &left, &right);
            self.release(&left);
            if i + 1 == ops.len() {
                self.release(&right);
                incoming.push(format!("[ {}, %{} ]", test.operand, self.current));
                self.jump(&end);
            } else {
                let (next, fail) = (self.label(), self.label());
                self.branch(&test.operand, &next, &fail);
                self.start(&fail);
                self.release(&right);
                incoming.push(format!("[ false, %{} ]", self.current));
                self.jump(&end);
                self.start(&next);
            }
            left = right;
        }
        self.start(&end);
        Value {
            ty: Type::Bool,
            operand: self.instruction(format!("phi i1 {}", incoming.join(", "))),
        }
    }

    fn boolean(&mut self, and: bool, values: &[Expr]) -> Value {
        let end = self.label();
        let mut incoming = Vec::new();
        for (i, expression) in values.iter().enumerate() {
            let value = self.expr(expression);
            incoming.push(format!("[ {}, %{} ]", value.operand, self.current));
            if i + 1 == values.len() {
                self.jump(&end);
            } else {
                let next = self.label();
                if and {
                    self.branch(&value.operand, &next, &end);
                } else {
                    self.branch(&value.operand, &end, &next);
                }
                self.start(&next);
            }
        }
        self.start(&end);
        Value {
            ty: Type::Bool,
            operand: self.instruction(format!("phi i1 {}", incoming.join(", "))),
        }
    }

    fn builtin(&mut self, builtin: &Builtin, expressions: &[Expr]) -> Value {
        let args = expressions
            .iter()
            .map(|arg| self.expr(arg))
            .collect::<Vec<_>>();
        let result = match builtin {
            Builtin::Input => self.call("relar_input", Type::Str, &[]),
            Builtin::Int => match args[0].ty {
                Type::Int => return args.into_iter().next().unwrap(),
                Type::Bool => {
                    let wide = self.instruction(format!("zext i1 {} to i64", args[0].operand));
                    let tagged = self.instruction(format!("shl i64 {wide}, 1"));
                    Value {
                        ty: Type::Int,
                        operand: self.instruction(format!("or i64 {tagged}, 1")),
                    }
                }
                Type::Str => self.call("relar_int_parse", Type::Int, &[&args[0]]),
                _ => unreachable!("int conversion was checked"),
            },
            Builtin::Len => self.call(
                if args[0].ty == Type::Str {
                    "relar_str_len"
                } else {
                    "relar_list_len"
                },
                Type::Int,
                &[&args[0]],
            ),
            Builtin::ListGet => self.call("relar_list_get", Type::Int, &[&args[0], &args[1]]),
            Builtin::Append => {
                self.void_call("relar_list_append", &[&args[0], &args[1]]);
                none()
            }
            Builtin::Pop => self.call("relar_list_pop", Type::Int, &[&args[0]]),
            Builtin::Print => {
                match args[0].ty {
                    Type::Int => self.void_call("relar_print_int", &[&args[0]]),
                    Type::Str => self.void_call("relar_print_str", &[&args[0]]),
                    Type::Bool => {
                        let byte = self.instruction(format!("zext i1 {} to i8", args[0].operand));
                        self.line(format!("call void @relar_print_bool(i8 {byte})"));
                    }
                    Type::None => self.void_call("relar_print_none", &[]),
                    Type::ListInt => unreachable!("list printing is rejected"),
                }
                none()
            }
        };
        for arg in &args {
            self.release(arg);
        }
        result
    }
}

fn small(value: i64) -> Value {
    Value {
        ty: Type::Int,
        operand: (((value as u64) << 1) | 1).to_string(),
    }
}

fn none() -> Value {
    Value {
        ty: Type::None,
        operand: "0".to_owned(),
    }
}

