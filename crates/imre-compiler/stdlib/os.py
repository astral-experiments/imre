def _fspath(path):
    """Return the path representation of a path-like object.

    If str or bytes is passed in, it is returned unchanged. Otherwise the
    os.PathLike interface is used to get the path representation. If the
    path representation is not str or bytes, TypeError is raised. If the
    provided path is not str, bytes, or os.PathLike, TypeError is raised.
    """
    if isinstance(path, (str, bytes)):
        return path

    # Work from the object's type to match method resolution of other magic
    # methods.
    path_type = type(path)
    try:
        path_repr = path_type.__fspath__(path)
    except AttributeError:
        if hasattr(path_type, '__fspath__'):
            raise
        else:
            raise TypeError("expected str, bytes or os.PathLike object, "
                            "not " + path_type.__name__)
    except TypeError:
        if path_type.__fspath__ is None:
            raise TypeError("expected str, bytes or os.PathLike object, "
                            "not " + path_type.__name__) from None
        else:
            raise
    if isinstance(path_repr, (str, bytes)):
        return path_repr
    else:
        raise TypeError("expected {}.__fspath__() to return str or bytes, "
                        "not {}".format(path_type.__name__,
                                        type(path_repr).__name__))


class PathLike(abc.ABC):

    """Abstract base class for implementing the file system path protocol."""

    __slots__ = ()

    @abc.abstractmethod
    def __fspath__(self):
        """Return the file system path representation of the object."""
        raise NotImplementedError

    @classmethod
    def __subclasshook__(cls, subclass):
        if cls is PathLike:
            return _check_methods(subclass, '__fspath__')
        return NotImplemented

    __class_getitem__ = classmethod(GenericAlias)


_env_encoding = sys.getfilesystemencoding()


def _encode_env(value):
    if not isinstance(value, str):
        raise TypeError("str expected, not %s" % type(value).__name__)
    return value.encode(_env_encoding, "surrogateescape")


def _decode_env(value):
    return value.decode(_env_encoding, "surrogateescape")


def _check_bytes(value):
    if not isinstance(value, bytes):
        raise TypeError("bytes expected, not %s" % type(value).__name__)
    return value


class _Environ(_MutableMapping):
    def __init__(self, data, encode, decode):
        self._data = data
        self._encode = encode
        self._decode = decode

    def __getitem__(self, key):
        try:
            value = self._data[self._encode(key)]
        except KeyError:
            raise KeyError(key) from None
        return self._decode(value)

    def __setitem__(self, key, value):
        key = self._encode(key)
        value = self._encode(value)
        putenv(key, value)
        self._data[key] = value

    def __delitem__(self, key):
        encoded = self._encode(key)
        unsetenv(encoded)
        try:
            del self._data[encoded]
        except KeyError:
            raise KeyError(key) from None

    def __iter__(self):
        for key in list(self._data):
            yield self._decode(key)

    def __len__(self):
        return len(self._data)

    def __repr__(self):
        formatted_items = ", ".join(
            f"{self._decode(key)!r}: {self._decode(value)!r}"
            for key, value in self._data.items()
        )
        return f"environ({{{formatted_items}}})"

    def copy(self):
        return dict(self)

    def setdefault(self, key, value):
        if key not in self:
            self[key] = value
        return self[key]

    def __ior__(self, other):
        self.update(other)
        return self

    def __or__(self, other):
        if not isinstance(other, _Mapping):
            return NotImplemented
        new = dict(self)
        new.update(other)
        return new

    def __ror__(self, other):
        if not isinstance(other, _Mapping):
            return NotImplemented
        new = dict(other)
        new.update(self)
        return new


