//! Python AST node classes installed by the native runtime.

#[derive(Clone, Copy)]
pub enum DefaultField {
    Required,
    Optional,
    List,
    Load,
}

use DefaultField::{List, Load, Optional, Required};

pub struct Node {
    pub name: &'static str,
    pub qualified_name: &'static str,
    pub base: &'static str,
    pub fields: &'static [(&'static str, DefaultField)],
    pub positions: bool,
}

macro_rules! node {
    ($name:ident : $base:ident, $positions:expr; $($field:ident : $default:ident),*) => {
        Node {
            name: stringify!($name),
            qualified_name: concat!("ast.", stringify!($name)),
            base: stringify!($base),
            positions: $positions,
            fields: &[$((stringify!($field), $default)),*],
        }
    };
}

