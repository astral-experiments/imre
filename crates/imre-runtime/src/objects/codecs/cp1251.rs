//! Windows-1251. The upper Cyrillic alphabet is contiguous; the table covers
//! the remaining 64 bytes in CPython 3.14.5's Lib/encodings/cp1251.py.

const EXTENDED: [u16; 64] = [
    0x0402, 0x0403, 0x201a, 0x0453, 0x201e, 0x2026, 0x2020, 0x2021, 0x20ac, 0x2030, 0x0409, 0x2039,
    0x040a, 0x040c, 0x040b, 0x040f, 0x0452, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2013, 0x2014,
    0x0000, 0x2122, 0x0459, 0x203a, 0x045a, 0x045c, 0x045b, 0x045f, 0x00a0, 0x040e, 0x045e, 0x0408,
    0x00a4, 0x0490, 0x00a6, 0x00a7, 0x0401, 0x00a9, 0x0404, 0x00ab, 0x00ac, 0x00ad, 0x00ae, 0x0407,
    0x00b0, 0x00b1, 0x0406, 0x0456, 0x0491, 0x00b5, 0x00b6, 0x00b7, 0x0451, 0x2116, 0x0454, 0x00bb,
    0x0458, 0x0405, 0x0455, 0x0457,
];

pub(super) fn decode(byte: u8) -> Option<char> {
    match byte {
        0x00..=0x7f => Some(char::from(byte)),
        0x98 => None,
        0x80..=0xbf => char::from_u32(u32::from(EXTENDED[usize::from(byte - 0x80)])),
        0xc0..=0xff => char::from_u32(0x0410 + u32::from(byte - 0xc0)),
    }
}

pub(super) fn encode(ch: char) -> Option<u8> {
    match u32::from(ch) {
        code @ 0..=0x7f => Some(code as u8),
        code @ 0x0410..=0x044f => Some(0xc0 + (code - 0x0410) as u8),
        code => EXTENDED
            .iter()
            .position(|&mapped| u32::from(mapped) == code)
            .map(|index| 0x80 + index as u8),
    }
}
