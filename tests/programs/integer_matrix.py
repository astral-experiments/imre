def main() -> None:
    count = int(input())
    for case in range(count):
        a = int(input())
        b = int(input())
        print(a + b)
        print(a - b)
        print(a * b)
        print(a // b)
        print(a % b)
        print(-a)
        print(a < b)
        print(a <= b)
        print(a > b)
        print(a >= b)
        print(a == b)
        print(a != b)


main()
