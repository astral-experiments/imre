"""Generate Imre's typed stat module from the pinned CPython implementation."""

import argparse
import ast
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "upstream/Lib/stat.py"
DEST = HERE.parents[3] / "crates/imre-compiler/stdlib/stat/common.py"
HEADER = """# Generated by benchmarks/cpython_stdlib/full/stat/generate_module.py.
# Public modes go through CPython's accelerated unsigned mode_t boundary.

def _checked_mode(mode: int) -> int:
    if mode < 0:
        raise OverflowError("can't convert negative value to unsigned int")
    if mode > 18446744073709551615:
        raise OverflowError("Python int too large to convert to C unsigned long")
    if mode > _MODE_MAX:
        raise OverflowError("mode out of range")
    return mode
"""


def generate(*, pure=False):
    src = SOURCE.read_text()
    lines = src.splitlines(keepends=True)
    result = (
        ["# Typed CPython fallback for the blocked-_stat fixture."]
        if pure
        else [HEADER]
    )
    for node in ast.parse(src).body:
        if isinstance(node, ast.Assign):
            name = node.targets[0].id
            # These values depend on the platform's stat headers.
            if not pure and name in {"S_IFWHT", "SF_SETTABLE"}:
                continue
            if name == "_filemode_table":
                # The original table has groups of different lengths. Use
                # homogeneous lists while keeping every (mask, letter) pair.
                groups = [
                    ast.List(elts=list(group.elts), ctx=ast.Load())
                    for group in node.value.elts
                ]
                # A negative sentinel cannot match an unsigned mode on POSIX targets
                # without whiteouts. Apple has a real whiteout file type.
                if not pure:
                    groups[0].elts.append(
                        ast.parse("(_WHITEOUT_MASK, 'w')", mode="eval").body
                    )
                result.append("_filemode_table: list[list[tuple[int, str]]] = [")
                result.extend("    " + ast.unparse(group) + "," for group in groups)
                result.append("]")
            else:
                result.append(
                    "".join(lines[node.lineno - 1 : node.end_lineno]).rstrip()
                )
        elif isinstance(node, ast.FunctionDef):
            name = node.name
            ret = (
                "str"
                if name == "filemode"
                else ("bool" if name.startswith("S_IS") else "int")
            )
            positional = "" if pure else ", /"
            result.append(f"\ndef {name}(mode: int{positional}) -> {ret}:")
            statements = node.body[1:] if ast.get_docstring(node) else node.body
            if not pure and name in {
                "S_IMODE",
                "S_IFMT",
                "S_ISWHT",
                "S_ISDOOR",
                "S_ISPORT",
                "filemode",
            }:
                result.append("    mode = _checked_mode(mode)")
            if name == "S_ISWHT" and not pure:
                result.append("    return S_IFMT(mode) == _WHITEOUT_MASK")
            else:
                fn = "".join(lines[statements[0].lineno - 1 : node.end_lineno]).rstrip()
                if name == "filemode":
                    fn = fn.replace("    perm = []", "    perm: list[str] = []")
                result.append(fn)
    return "\n".join(result) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    out = generate()
    if args.check:
        if DEST.read_text() != out:
            raise SystemExit("regenerate the bundled stat implementation")
    else:
        DEST.parent.mkdir(parents=True, exist_ok=True)
        DEST.write_text(out)


if __name__ == "__main__":
    main()
